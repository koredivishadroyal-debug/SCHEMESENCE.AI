// Regional language fallback map for other Indian states & UTs
const LANGUAGE_FALLBACK_MAP: Partial<Record<Language, Language>> = {
  Kashmiri: 'Urdu',
  Dogri: 'Hindi',
  Maithili: 'Hindi',
  Konkani: 'Marathi',
  Santali: 'Hindi',
  Bodo: 'Assamese',
  Manipuri: 'Bengali',
  Nepali: 'Hindi',
  Sanskrit: 'Hindi',
  Sindhi: 'Hindi',
  Mizo: 'English',
  Khasi: 'English',
  Garo: 'English',
  Kokborok: 'Bengali',
  Ladakhi: 'Hindi',
};

export function getTranslation(key: string, lang: Language): string {
  const direct = TRANSLATIONS[lang]?.[key];
  if (direct) return direct;
  
  const fallbackLang = LANGUAGE_FALLBACK_MAP[lang];
  if (fallbackLang && TRANSLATIONS[fallbackLang]?.[key]) {
    return TRANSLATIONS[fallbackLang]![key];
  }
  
  return TRANSLATIONS['English']?.[key] || key;
}
